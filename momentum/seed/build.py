"""Build the shipped seed database from source, reproducibly.

The game starts from ``database/momentum.db``. This script rebuilds that file
from nothing: the schema, a career world generated by ``seed_career_mode`` with
a fixed seed, and every circuit in ``data/circuits_database.json``. It refuses
to leave any play state (races, results, championships, career progress) in
the result, so the committed database is only ever a starting point.

Usage::

    python scripts/build_seed_database.py                 # rebuild database/momentum.db
    python scripts/build_seed_database.py --output /tmp/world.db --seed 7
    python scripts/build_seed_database.py --teams-per-discipline 10 --drivers 150
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

from momentum.config import DATABASE_PATH, DISCIPLINES
from momentum.database.database_manager import DatabaseManager
from momentum.seed import circuits as import_circuits
from momentum.seed import world
from momentum.services.finance_service import OWNER_FUNDING, FinanceService

# Tables that describe things that happened, rather than the world as shipped.
PLAY_STATE_TABLES: tuple[str, ...] = (
    "championships",
    "races",
    "race_results",
    "career_player_profiles",
    "career_world_state",
    "career_championships",
    "career_races",
    "career_race_results",
    "team_car_upgrades",
    "team_facility_upgrades",
    "team_audit_log",
    "ai_offseason_spending",
)

DEFAULT_TEAMS_PER_DISCIPLINE = 100


def _table_names(conn) -> set[str]:
    rows = conn.execute("SELECT name FROM sqlite_master WHERE type = 'table'").fetchall()
    return {str(row[0]) for row in rows}


def play_state_counts(db: DatabaseManager) -> dict[str, int]:
    """Row counts for every play-state table that exists."""
    counts: dict[str, int] = {}
    with db.get_connection() as conn:
        present = _table_names(conn)
        for table in PLAY_STATE_TABLES:
            if table in present:
                counts[table] = int(conn.execute(f"SELECT COUNT(1) FROM {table}").fetchone()[0])
    return counts


def _pin_timestamps(db: DatabaseManager) -> None:
    """Replace CURRENT_TIMESTAMP defaults so two builds are byte-for-byte alike."""
    stamp = f"{world.SEED_REFERENCE_DATE.isoformat()} 00:00:00"
    with db.get_connection() as conn:
        for table in _table_names(conn):
            columns = {row[1] for row in conn.execute(f"PRAGMA table_info({table})")}
            stamped = [c for c in ("created_at", "updated_at") if c in columns]
            if stamped:
                assignments = ", ".join(f"{c} = ?" for c in stamped)
                conn.execute(f"UPDATE {table} SET {assignments}", [stamp] * len(stamped))
        conn.commit()


def build(
    output: Path,
    seed: int = world.DEFAULT_SEED,
    teams_per_discipline: int = DEFAULT_TEAMS_PER_DISCIPLINE,
    drivers: int | None = None,
    staff: int | None = None,
) -> dict[str, int]:
    """Create a fresh seed database at ``output`` and return its table counts."""
    output = Path(output)
    if os.environ.get("PYTHONHASHSEED") != "0":
        # Some Faker providers draw from set-derived lists, so the build is only
        # reproducible under a fixed hash seed. Callers need not know that.
        return _build_in_pinned_process(output, seed, teams_per_discipline, drivers, staff)
    output.parent.mkdir(parents=True, exist_ok=True)
    for suffix in ("", "-journal", "-wal", "-shm"):
        stale = Path(str(output) + suffix)
        if stale.exists():
            stale.unlink()

    world.seed_world(seed)
    disciplines = list(DISCIPLINES.keys())
    if staff is None:
        staff = teams_per_discipline * len(disciplines) * world.STAFF_SLOTS_PER_TEAM
    if drivers is None:
        drivers = world.default_driver_count(teams_per_discipline, disciplines)

    db = DatabaseManager(db_path=str(output), seed_from_bundle=False)
    world.seed_drivers(db, drivers, disciplines)
    world.seed_teams(db, teams_per_discipline, disciplines)
    world.seed_staff(db, staff)
    world.assign_staff_contracts(db, disciplines)
    world.assign_driver_contracts(db, disciplines)
    world.assign_tiers_by_strength(db, disciplines)
    world.adjust_drivers_by_tier(db)

    if import_circuits.main(["--db", str(output), "--mode", "insert"]) != 0:
        raise RuntimeError("circuit import failed")

    leftovers = {table: n for table, n in play_state_counts(db).items() if n}
    if leftovers:
        raise RuntimeError(f"seed database contains play state: {leftovers}")
    # The ledger may only hold each team's opening capital, and must add up.
    with db.get_connection() as conn:
        categories = {
            str(row[0])
            for row in conn.execute("SELECT DISTINCT category FROM team_budget_transactions")
        }
    if categories - {OWNER_FUNDING}:
        raise RuntimeError(f"seed ledger has non-opening transactions: {categories}")
    mismatched = FinanceService(db).reconcile()
    if mismatched:
        raise RuntimeError(f"seed balances do not match the ledger: {mismatched[:3]}")

    _pin_timestamps(db)
    with db.get_connection() as conn:
        conn.execute("VACUUM")
    return _counts(db)


def _counts(db: DatabaseManager) -> dict[str, int]:
    with db.get_connection() as conn:
        return {
            table: int(conn.execute(f"SELECT COUNT(1) FROM {table}").fetchone()[0])
            for table in ("drivers", "teams", "staff_members", "tracks")
        }


def _build_in_pinned_process(
    output: Path,
    seed: int,
    teams_per_discipline: int,
    drivers: int | None,
    staff: int | None,
) -> dict[str, int]:
    # The child runs from the repository root, so a relative output path must
    # be anchored to the caller's directory before it crosses over. absolute()
    # rather than resolve(): a symlinked output is replaced, not its target.
    output = Path(output).absolute()
    argv = [
        sys.executable,
        "-m",
        "momentum.seed.build",
        "--output",
        str(output),
        "--seed",
        str(seed),
        "--teams-per-discipline",
        str(teams_per_discipline),
    ]
    if drivers is not None:
        argv += ["--drivers", str(drivers)]
    if staff is not None:
        argv += ["--staff", str(staff)]
    subprocess.run(
        argv,
        check=True,
        cwd=str(Path(__file__).resolve().parents[2]),
        env=dict(os.environ, PYTHONHASHSEED="0"),
    )
    return _counts(DatabaseManager(db_path=str(output)))


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--output", default=DATABASE_PATH, help="Database file to (re)build")
    parser.add_argument("--seed", type=int, default=world.DEFAULT_SEED)
    parser.add_argument("--teams-per-discipline", type=int, default=DEFAULT_TEAMS_PER_DISCIPLINE)
    parser.add_argument(
        "--drivers", type=int, default=None, help="Default: every seat plus 15%% free agents"
    )
    parser.add_argument("--staff", type=int, default=None, help="Default: three per team")
    args = parser.parse_args(argv)

    counts = build(
        Path(args.output),
        seed=args.seed,
        teams_per_discipline=args.teams_per_discipline,
        drivers=args.drivers,
        staff=args.staff,
    )
    size_mb = os.path.getsize(args.output) / (1024 * 1024)
    print(f"\nSeed database built: {args.output} ({size_mb:.1f} MB, seed {args.seed})")
    for table, count in counts.items():
        print(f"  {table}: {count}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
